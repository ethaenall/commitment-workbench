// Reproducible source/build compatibility identities, not server attestation.
// Generated output is excluded to avoid a self-referential digest.
import { createHash } from "node:crypto";
import { lstatSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const output = "packages/engine/src/workflows/build-identity.ts";
const sha = (data) => createHash("sha256").update(data).digest("hex");
function files(path) {
  const stat = lstatSync(join(root, path));
  if (stat.isSymbolicLink()) throw new Error(`Identity input must not be a symlink: ${path}`);
  if (stat.isDirectory()) return readdirSync(join(root, path)).sort().flatMap((name) => files(`${path}/${name}`));
  return path === output ? [] : [path];
}
const paths = [
  ...files("packages/engine/src"), ...files("packages/contracts/src"), ...files("packages/audit/src"),
  "packages/engine/scripts/build.mjs", "packages/engine/scripts/workflow-identity.mjs",
  "packages/engine/scripts/stage-rlm-runtime.mjs", // Includes exact private QuickJS vendor pins.
  "packages/engine/package.json", "packages/engine/tsconfig.json", "packages/engine/tsconfig.build.json",
  "packages/engine/tsconfig.daemon.json", "packages/engine/wrangler.toml", "package-lock.json",
].sort();
const entries = paths.map((path) => [path, sha(readFileSync(join(root, path)))]);
const sourceHash = sha(JSON.stringify(entries));
const contractPaths = ["packages/contracts/src/workflows.ts", "packages/engine/src/workflows/commitment-handoff.ts"];
const contractHash = sha(JSON.stringify(contractPaths.map((path) => [path, sha(readFileSync(join(root, path)))])));
const generated = "// SPDX-License-Identifier: AGPL-3.0-only\n" +
  "// Generated by scripts/workflow-identity.mjs. Do not hand-edit.\n" +
  "// All engine/contracts/audit source + pinned build inputs; no credentials or timestamps.\n" +
  `export const WORKFLOW_SOURCE_HASH = ${JSON.stringify(sourceHash)};\n` +
  `export const WORKFLOW_BUILD_HASH = ${JSON.stringify(sha("workflow-runner\0" + sourceHash))};\n` +
  `export const REFINEMENT_VALIDATOR_BUILD_HASH = ${JSON.stringify(sha("refinement-validator\0" + sourceHash))};\n` +
  `export const COMMITMENT_CONTRACT_HASH = ${JSON.stringify(contractHash)};\n`;
const target = join(root, output);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) {
    console.error("Workflow identity is stale. Run the engine codegen recipe before validation/build.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, generated);
  console.log(`Workflow identity: ${sourceHash.slice(0, 12)} (${entries.length} source/build inputs; ${relative(root, target)})`);
}
